"""Readable equivalents of legacy Symbol-font private-use code points."""
import unicodedata

_SYMBOL={0x61:'α',0x62:'β',0x67:'γ',0x64:'δ',0x65:'ε',0x68:'η',0x6b:'κ',0x6c:'λ',0x6d:'μ',0x6e:'ν',
         0x70:'π',0x71:'θ',0x72:'ρ',0x73:'σ',0x74:'τ',0x66:'φ',0x77:'ω',0x53:'Σ',0xa3:'≤',0xb3:'≥',
         0xb4:'×',0xb7:'·',0xb1:'±',0xa5:'∞',0xb0:'°',0xae:'→',0xac:'←',0xd6:'√',0xe5:'∑',0xf2:'∫',0xce:'∈',0xcf:'∉'}

def readable_math(text):
    return ''.join(_SYMBOL.get(ord(c)-0xf000,c) if 0xf000<=ord(c)<=0xf0ff else c for c in text)

def equivalent_math_text(text):
    return unicodedata.normalize('NFKC',readable_math(text))
